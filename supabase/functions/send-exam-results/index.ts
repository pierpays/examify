import "jsr:@supabase/functions-js/edge-runtime.d.ts";
import { createClient } from "jsr:@supabase/supabase-js@2";

const RESEND_API_KEY = Deno.env.get("RESEND_API_KEY");

Deno.serve(async (req) => {
  try {
    if (req.method !== "POST") {
      return new Response("Method not allowed", { status: 405 });
    }

    const authHeader = req.headers.get("Authorization");

    if (!authHeader) {
      return new Response("Unauthorized", { status: 401 });
    }

    const { attemptId } = await req.json();

    if (!attemptId) {
      return new Response("Missing attemptId", { status: 400 });
    }

    if (!RESEND_API_KEY) {
      throw new Error("RESEND_API_KEY is not configured.");
    }

    const supabase = createClient(
      Deno.env.get("SUPABASE_URL")!,
      Deno.env.get("SUPABASE_ANON_KEY")!,
      {
        global: {
          headers: {
            Authorization: authHeader,
          },
        },
      },
    );

    const { data, error } = await supabase.rpc(
      "get_exam_result_email_payload",
      {
        target_attempt_id: attemptId,
      },
    );

    if (error) {
      throw error;
    }

    const result = Array.isArray(data) ? data[0] : data;

    if (!result) {
      return new Response("Result not found", { status: 404 });
    }

    const sendEmail = async (
      to: string,
      subject: string,
      html: string,
    ) => {
      const response = await fetch("https://api.resend.com/emails", {
        method: "POST",
        headers: {
          Authorization: `Bearer ${RESEND_API_KEY}`,
          "Content-Type": "application/json",
        },
        body: JSON.stringify({
          from: "Examify <results@examify.app>",
          to: [to],
          subject,
          html,
        }),
      });

      if (!response.ok) {
        const body = await response.text();
        throw new Error(`Email delivery failed: ${body}`);
      }
    };

    const status = result.passed ? "Passed" : "Not passed";

    const emailHtml = `
      <div style="font-family:Arial,sans-serif;max-width:600px;margin:auto">
        <h1>Exam Results</h1>

        <h2>${result.exam_title}</h2>

        <p>Your final score:</p>

        <p style="font-size:36px;font-weight:bold;margin:12px 0">
          ${Number(result.score_percent).toFixed(2)}%
        </p>

        <p>
          <strong>${status}</strong>
        </p>

        <p>
          Passing score: ${result.passing_score}%
        </p>

        <hr style="margin:24px 0;border:0;border-top:1px solid #ddd" />

        <p style="color:#666;font-size:13px">
          This result was generated by Examify.
        </p>
      </div>
    `;

    const sent = {
      student: false,
      teacher: false,
    };

    if (result.email_student && result.student_email) {
      await sendEmail(
        result.student_email,
        `Your ${result.exam_title} results`,
        emailHtml,
      );

      sent.student = true;
    }

    if (result.email_teacher && result.teacher_email) {
      const teacherHtml = `
        <div style="font-family:Arial,sans-serif;max-width:600px;margin:auto">
          <h1>Student Exam Result</h1>

          <h2>${result.exam_title}</h2>

          <p>
            A student has completed your exam.
          </p>

          <p style="font-size:36px;font-weight:bold;margin:12px 0">
            ${Number(result.score_percent).toFixed(2)}%
          </p>

          <p>
            <strong>${status}</strong>
          </p>

          <p>
            Passing score: ${result.passing_score}%
          </p>
        </div>
      `;

      await sendEmail(
        result.teacher_email,
        `New result for ${result.exam_title}`,
        teacherHtml,
      );

      sent.teacher = true;
    }

    return new Response(
      JSON.stringify({
        success: true,
        sent,
      }),
      {
        headers: {
          "Content-Type": "application/json",
        },
      },
    );
  } catch (error) {
    console.error(error);

    return new Response(
      JSON.stringify({
        error:
          error instanceof Error
            ? error.message
            : "Unknown error",
      }),
      {
        status: 500,
        headers: {
          "Content-Type": "application/json",
        },
      },
    );
  }
});
